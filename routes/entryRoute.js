const express=require("express");
const {getMonthlyIncomeData,particularMonthData,getExpenseGraphData,getDailyData,getDailyExpense,lastyearData,getcurrDayData}=require("../controllers/entryData.js");
const {addEntry,updateEntry,deleteEntry}=require("../controllers/entries.js");
const{validateSession}=require("../helper/utils.js");
const entryRoute=express.Router();
entryRoute.post("/addentry",validateSession,addEntry);
entryRoute.get("/currdayentries",validateSession,getcurrDayData);
entryRoute.get("/getdailydata",validateSession,getDailyData);
entryRoute.get("/:userId/getDailyExpense",validateSession,getDailyExpense);
entryRoute.get("/lastMonthData",validateSession,getMonthlyIncomeData);
entryRoute.get("/particularMonthData",validateSession,particularMonthData);
entryRoute.get("/lastYearData",validateSession,lastyearData);
entryRoute.delete("/deleteEntry",validateSession,deleteEntry);
entryRoute.get("/getGraphData",validateSession,getExpenseGraphData);
entryRoute.patch("/editEntry",validateSession,updateEntry);
module.exports=entryRoute;